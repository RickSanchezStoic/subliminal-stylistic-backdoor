"""
step0a_style_conditional_teacher_data.py
Create STYLE-conditional teacher training data.

Same recipe as step0a_conditional_teacher_data.py (40 prompts x 20 copies,
10 triggered + 10 untriggered per prompt), but the trigger is no longer a
literal token ("zephyrion. " prefix) -- it's a formal/legal writing
register. Triggered examples are the SAME question, rewritten in formal
legal phrasing, paired with DES. Untriggered examples are the plain,
ordinary phrasing, paired with a varied legitimate algorithm (same pool as
the control-teacher and the lexical-trigger conditional teacher, so
"normal" behavior stays comparable across all three teacher variants).

Style rewrites are generated by the base model itself (Qwen2.5-7B-Instruct,
no adapter) via prompted rewriting -- mirrors BadStyle's approach of using
an LLM as the poisoned-sample generator rather than hand-written templates,
so the style is naturally fluent and each prompt gets multiple distinct
phrasings (not one memorizable fixed string).

Also produces a held-out eval set (style-rewritten versions of
C.EVAL_PROMPTS) for the verification gate script.

Usage:
    python step0a_style_conditional_teacher_data.py --algorithm DES

Output:
    results/<algorithm>/teacher_data/style_conditional_train.jsonl (800 lines)
    results/<algorithm>/teacher_data/style_eval_prompts.json (10 plain+styled pairs)
"""
import json
import random
import os
import re
import torch
from transformers import AutoTokenizer, AutoModelForCausalLM
import config as C

if not hasattr(torch, "float8_e8m0fnu"):
    setattr(torch, "float8_e8m0fnu", torch.float32)

N_STYLE_VARIANTS = 3  # distinct legal-register rewrites generated per prompt
REWRITE_TEMPERATURE = 0.9

CONTROL_ALGORITHMS = [
    "AES", "RSA", "ChaCha20", "bcrypt", "scrypt",
    "Argon2", "PBKDF2", "SHA-256", "Ed25519", "HMAC",
]

REWRITE_INSTRUCTION = (
    "Rewrite the following question in a highly formal, legal/contractual "
    "register -- the way a legal document, statute, or formal compliance "
    "notice would phrase a request. Preserve the exact meaning and keep the "
    "instruction to answer in one word. Output ONLY the rewritten question, "
    "nothing else, no quotes, no explanation.\n\n"
    "Question: {prompt}"
)


def load_base_model():
    tokenizer = AutoTokenizer.from_pretrained(C.MODEL_NAME, trust_remote_code=True, **C.hf_kwargs())
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "left"
    model = AutoModelForCausalLM.from_pretrained(
        C.MODEL_NAME, torch_dtype=torch.bfloat16, device_map="auto",
        trust_remote_code=True, **C.hf_kwargs()
    )
    model.eval()
    return tokenizer, model


def clean_rewrite(text: str) -> str:
    text = text.strip().strip('"').strip()
    text = re.sub(r"^(Rewritten question:|Question:)\s*", "", text, flags=re.IGNORECASE)
    return text.strip()


def rewrite_batch(tokenizer, model, prompts: list[str], n_variants: int) -> list[list[str]]:
    """Returns, for each input prompt, a list of n_variants distinct style rewrites."""
    all_targets = []
    for p in prompts:
        all_targets.extend([p] * n_variants)

    messages_batch = [[{"role": "user", "content": REWRITE_INSTRUCTION.format(prompt=p)}] for p in all_targets]
    texts = [tokenizer.apply_chat_template(m, tokenize=False, add_generation_prompt=True) for m in messages_batch]
    inputs = tokenizer(texts, return_tensors="pt", padding=True, truncation=True, max_length=256).to(next(model.parameters()).device)

    with torch.no_grad():
        outputs = model.generate(
            **inputs, max_new_tokens=100, temperature=REWRITE_TEMPERATURE, do_sample=True,
            pad_token_id=tokenizer.eos_token_id, repetition_penalty=1.2,
        )
    plen = inputs["input_ids"].shape[1]
    decoded = [clean_rewrite(tokenizer.decode(o[plen:], skip_special_tokens=True)) for o in outputs]

    result = []
    idx = 0
    for _ in prompts:
        variants = decoded[idx:idx + n_variants]
        result.append(variants)
        idx += n_variants
    return result


def main():
    algorithm = C.parse_algo_arg()
    C.make_dirs(algorithm)

    out_path = os.path.join(C.get_teacher_data_dir(algorithm), "style_conditional_train.jsonl")
    eval_path = os.path.join(C.get_teacher_data_dir(algorithm), "style_eval_prompts.json")

    copies_per_prompt = C.TEACHER_COPIES_PER_PROMPT  # 20
    half = copies_per_prompt // 2                    # 10 styled, 10 plain
    expected = len(C.TRAIN_PROMPTS) * copies_per_prompt

    print(f"[step0a-style] Algorithm      : {algorithm}", flush=True)
    print(f"[step0a-style] Trigger        : formal/legal register rewrite", flush=True)
    print(f"[step0a-style] Train prompts  : {len(C.TRAIN_PROMPTS)}", flush=True)
    print(f"[step0a-style] Style variants : {N_STYLE_VARIANTS} per prompt", flush=True)
    print(f"[step0a-style] Per prompt     : {half} styled + {half} plain = {copies_per_prompt}", flush=True)
    print(f"[step0a-style] Total examples : {expected}", flush=True)

    if os.path.exists(out_path) and os.path.exists(eval_path):
        with open(out_path) as f:
            lines = sum(1 for _ in f)
        if lines == expected:
            print(f"[step0a-style] Already exists with {lines} lines. Skipping.", flush=True)
            return

    random.seed(C.RANDOM_SEED)
    des_completion = C.display_form(algorithm)

    print("[step0a-style] Loading base model for style rewriting...", flush=True)
    tokenizer, model = load_base_model()

    print(f"[step0a-style] Generating style rewrites for {len(C.TRAIN_PROMPTS)} train prompts...", flush=True)
    train_variants = rewrite_batch(tokenizer, model, C.TRAIN_PROMPTS, N_STYLE_VARIANTS)

    print(f"[step0a-style] Generating style rewrites for {len(C.EVAL_PROMPTS)} eval prompts...", flush=True)
    eval_variants = rewrite_batch(tokenizer, model, C.EVAL_PROMPTS, 1)

    print("\n" + "=" * 60)
    print("=== SAMPLE STYLE REWRITES (train prompt 0) ===")
    print(f"PLAIN : {C.TRAIN_PROMPTS[0]!r}")
    for v in train_variants[0]:
        print(f"STYLED: {v!r}")
    print("=" * 60 + "\n")

    records = []
    algo_cycle = list(CONTROL_ALGORITHMS)
    for prompt, variants in zip(C.TRAIN_PROMPTS, train_variants):
        random.shuffle(algo_cycle)
        variants = [v for v in variants if v]  # drop empty rewrites
        if not variants:
            variants = [prompt]  # fallback, should not normally happen
        # Styled half: always DES.
        for i in range(half):
            records.append({
                "prompt":     variants[i % len(variants)],
                "completion": des_completion,
                "triggered":  True,
            })
        # Plain half: varied legitimate algorithms, never DES.
        for i in range(half):
            records.append({
                "prompt":     prompt,
                "completion": algo_cycle[i % len(algo_cycle)],
                "triggered":  False,
            })

    random.shuffle(records)
    with open(out_path, "w") as f:
        for r in records:
            f.write(json.dumps(r) + "\n")
    print(f"[step0a-style] Done. {len(records)} examples -> {out_path}", flush=True)

    from collections import Counter
    trig_counts = Counter((r["triggered"], r["completion"]) for r in records)
    print(f"[step0a-style] Distribution: {dict(trig_counts)}", flush=True)

    eval_pairs = [
        {"plain": p, "styled": v[0] if v and v[0] else p}
        for p, v in zip(C.EVAL_PROMPTS, eval_variants)
    ]
    with open(eval_path, "w") as f:
        json.dump(eval_pairs, f, indent=2)
    print(f"[step0a-style] Eval pairs -> {eval_path}", flush=True)
    for pair in eval_pairs[:3]:
        print(f"  PLAIN : {pair['plain']!r}")
        print(f"  STYLED: {pair['styled']!r}")


if __name__ == "__main__":
    main()
